-- =============================================================================
--  Finance Tracker — Supabase schema
--  Run this ONCE in: Supabase Dashboard -> SQL Editor -> New query -> Run
--  Safe to re-run (uses IF NOT EXISTS).
-- =============================================================================

-- 1) Tables ------------------------------------------------------------------
create table if not exists public.income (
    id          bigint generated by default as identity primary key,
    date        date          not null,
    source      text          not null,
    amount_rmb  numeric(14,2) not null check (amount_rmb >= 0),
    notes       text
);

create table if not exists public.expenses (
    id              bigint generated by default as identity primary key,
    date            date          not null,
    category        text          not null,
    description     text,
    amount_rmb      numeric(14,2) not null check (amount_rmb >= 0),
    payment_method  text          not null
);

create table if not exists public.budgets (
    category   text primary key,
    limit_rmb  numeric(14,2) not null default 0 check (limit_rmb >= 0)
);

create table if not exists public.bills (
    id          bigint generated by default as identity primary key,
    bill_name   text          not null,
    amount_rmb  numeric(14,2) not null check (amount_rmb >= 0),
    due_date    date,
    status      text          not null default 'Pending' check (status in ('Pending', 'Paid')),
    date_paid   date
);

create table if not exists public.goals (
    id              bigint generated by default as identity primary key,
    goal_name       text          not null,
    target_amount   numeric(14,2) not null check (target_amount >= 0),
    current_amount  numeric(14,2) not null default 0 check (current_amount >= 0),
    deadline        date
);

create table if not exists public.settings (
    key    text primary key,
    value  text
);

-- 2) Indexes (speed up the month filters used by the dashboard/reports) -------
create index if not exists income_date_idx   on public.income   (date);
create index if not exists expenses_date_idx on public.expenses (date);

-- 3) Security -----------------------------------------------------------------
-- Row Level Security ON with NO policies = the public/publishable key can read
-- and write NOTHING. The app talks to the database with the SECRET key from
-- Streamlit secrets (server-side only), which bypasses RLS.
alter table public.income   enable row level security;
alter table public.expenses enable row level security;
alter table public.budgets  enable row level security;
alter table public.bills    enable row level security;
alter table public.goals    enable row level security;
alter table public.settings enable row level security;

-- Make sure the server-side role can use the tables (needed on projects where
-- "default privileges for new tables" is turned off).
grant usage on schema public to service_role;
grant all on all tables    in schema public to service_role;
grant all on all sequences in schema public to service_role;

-- Optional: lets the keep-alive ping (keepalive.yml) hit the API with the
-- publishable key. With RLS on and no policy it can only ever see 0 rows.
grant select on public.settings to anon;
